/** Mapa id → definición. */
export const AGENT_BY_ID: Record<string, AgentDef> = Object.fromEntries(
  AGENTS.map((a) => [a.id, a]),
);

/** Adivina el agente por un nombre de archivo o carpeta raíz del export. */
export function detectAgentFromName(name: string): AgentDef | null {
  for (const a of AGENTS) {
    if (a.detect && a.detect.test(name)) return a;
  }
  return null;
}
