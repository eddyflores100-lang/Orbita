// BÓVEDA — registro universal de agentes de IA
// Única fuente de verdad: cada agente que sabe importar BÓVEDA vive aquí,
// con su página oficial de export/autenticación y el formato que acepta.
// types.ts construye los orígenes (Sources) a partir de este registro.

export type AgentCategory = "destacado" | "asistente" | "codigo" | "china";

export interface AgentDef {
  /** id de origen (viaja en el sobre de cada memoria) */
  id: string;
  name: string;
  maker: string;
  category: AgentCategory;
  /** monograma corto para el avatar en la UI */
  mono: string;
  /** dónde pedir el export, en la UI del propio agente */
  hint: string;
  /** deep-link a la página oficial donde el usuario se autentica y pide el export */
  url: string | null;
  /** qué archivo(s) acepta BÓVEDA de este agente */
  formats: string;
  /** cómo llega el dato: zip, json, texto pegado o archivos locales */
  method: "zip" | "json" | "pegar" | "local";
  /** pista por nombre de archivo/carpeta para autodetectar el origen */
  detect?: RegExp;
  /** tiempo típico hasta que llega el archivo tras pedirlo */
  wait?: string;
}

